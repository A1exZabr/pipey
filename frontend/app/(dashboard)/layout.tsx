'use client';

import { useEffect, useState } from 'react';
import { useRouter, usePathname } from 'next/navigation';
import Link from 'next/link';
import Image from 'next/image';
import { useAuth } from '@/lib/auth-context';
import { MobileNav } from '@/components/MobileNav';

const navigation = [
  { name: 'Dashboard', href: '/dashboard', icon: DashboardIcon },
  { name: 'Contacts', href: '/contacts', icon: ContactsIcon },
  { name: 'Pipeline', href: '/pipeline', icon: PipelineIcon },
  { name: 'Inbox', href: '/inbox', icon: InboxIcon },
  { name: 'Documents', href: '/artifacts', icon: DocumentsIcon },
  { name: 'Integrations', href: '/integrations', icon: IntegrationsIcon },
  { name: 'Analytics', href: '/analytics', icon: AnalyticsIcon },
  { name: 'Team', href: '/team', icon: TeamIcon },
  { name: 'Settings', href: '/settings', icon: SettingsIcon },
];

export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  const { user, isLoading, logout } = useAuth();
  const router = useRouter();
  const pathname = usePathname();

  useEffect(() => {
    if (!isLoading && !user) {
      router.push('/auth/login');
    }
    // Redirect to onboarding if not completed
    if (!isLoading && user && !user.organizations?.[0]?.onboardingCompleted) {
      router.push('/onboarding');
    }
  }, [user, isLoading, router]);

  if (isLoading) {
    return (
      <div className="min-h-screen flex items-center justify-center">
        <div className="w-8 h-8 border-2 border-blue-500 border-t-transparent rounded-full animate-spin" />
      </div>
    );
  }

  if (!user) return null;

  return (
    <div className="min-h-screen flex">
      {/* Sidebar - Hidden on mobile */}
      <aside className="hidden md:flex w-64 glass fixed h-screen p-4 flex-col">
        {/* Logo */}
        <div className="flex items-center px-4 py-3 mb-6">
          <Image
            src="/Pipey_logo.png"
            alt="Pipey"
            width={150}
            height={40}
            className="h-8 w-auto"
            priority
          />
        </div>

        {/* Navigation */}
        <nav className="flex-1 space-y-1">
          {navigation.map((item) => {
            const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
            return (
              <Link
                key={item.name}
                href={item.href}
                className={'sidebar-item' + (isActive ? ' active' : '')}
              >
                <item.icon className="w-5 h-5" />
                <span className="font-medium">{item.name}</span>
              </Link>
            );
          })}
        </nav>

        {/* User */}
        <div className="border-t border-black/5 pt-4 mt-4">
          <div className="flex items-center gap-3 px-4 py-2">
            <div className="w-9 h-9 rounded-full bg-gradient-to-br from-purple-400 to-pink-400 flex items-center justify-center">
              <span className="text-white font-medium text-sm">
                {user.email.charAt(0).toUpperCase()}
              </span>
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium truncate">{user.email}</p>
              <p className="text-xs text-gray-500 truncate">
                {user.organizations[0]?.name || 'Organization'}
              </p>
            </div>
          </div>
          <button
            onClick={logout}
            className="sidebar-item w-full mt-2 text-red-500 hover:bg-red-50"
          >
            <LogoutIcon className="w-5 h-5" />
            <span className="font-medium">Log out</span>
          </button>
        </div>
      </aside>

      {/* Main content */}
      <main className="flex-1 md:ml-64 p-4 md:p-8 pb-20 md:pb-8">
        {children}
      </main>

      {/* Mobile Navigation */}
      <MobileNav />
    </div>
  );
}

